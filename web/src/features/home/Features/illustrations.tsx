export type FeatureCardKey =
  | 'singleApi'
  | 'security'
  | 'globalEdge'
  | 'latency'
  | 'failover'

export function FeatureIllustration({
  cardKey,
  gid,
}: {
  cardKey: FeatureCardKey
  gid: string
}) {
  switch (cardKey) {
    case 'singleApi':
      return <SingleApiIcon gid={gid} />
    case 'security':
      return <SecurityIcon gid={gid} />
    case 'globalEdge':
      return <GlobalEdgeIcon gid={gid} />
    case 'latency':
      return <LatencyIcon gid={gid} />
    case 'failover':
      return <FailoverIcon gid={gid} />
  }
}
